    public static IReadOnlyList<Country> All => AllCountries;

    private static readonly IReadOnlyDictionary<string, Country> ByCodeLookup =
        AllCountries.ToDictionary(c => c.Code, StringComparer.OrdinalIgnoreCase);

    public static bool IsKnown(string? code) =>
        !string.IsNullOrWhiteSpace(code) && ByCodeLookup.ContainsKey(code.Trim());

    public static Country? Find(string? code) =>
        !string.IsNullOrWhiteSpace(code) && ByCodeLookup.TryGetValue(code.Trim(), out var country) ? country : null;

    /// <summary>Falls back to the raw code, so an unknown value still renders.</summary>
    public static string NameOf(string? code) => Find(code)?.Name ?? (code ?? "Unknown");

    public static string FlagOf(string? code) => Find(code)?.Flag ?? "\U0001F3F3";
