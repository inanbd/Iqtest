namespace IqTest.Application.Reference;

/// <summary>A country a participant can pick when joining the board.</summary>
/// <param name="Code">ISO 3166-1 alpha-2, upper case.</param>
/// <param name="Name">English short name.</param>
public sealed record Country(string Code, string Name)
{
    /// <summary>
    /// The flag emoji for this country, built from the regional indicator
    /// letters of its code, so no image assets are needed.
    /// </summary>
    public string Flag => string.Concat(Code.Select(c => char.ConvertFromUtf32(0x1F1E6 + (c - 'A'))));
}

